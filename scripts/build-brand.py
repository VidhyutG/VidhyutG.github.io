"""Build the Vidi vector masters, canvas geometry, and reusable identity kit.

The hand-drawn contours in assets/brand/geometry.json are the single source.
Python + Pillow are used for raster exports; no network access is needed.
"""
from pathlib import Path
from zipfile import ZipFile, ZIP_DEFLATED
import json
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
BRAND = ROOT / "assets/brand"
OUTPUT = ROOT.parent / "output/brand"
MODEL = json.loads((BRAND / "geometry.json").read_text())


def parts_for(kind):
    return [p for p in MODEL["parts"] if kind == "wordmark" or p["id"] in MODEL["stamp"]["parts"]]


def path_data(part):
    return " ".join("M" + " L".join(f"{x} {y}" for x, y in contour) + " Z" for contour in part["contours"])


def paths(kind, ink, accent):
    return "\n".join(
        f'<path d="{path_data(p)}" fill="{accent if p.get("accent") else ink}" fill-rule="evenodd"/>'
        for p in parts_for(kind)
    )


def svg(kind, ink, accent):
    box = " ".join(map(str, MODEL[kind]["viewBox"]))
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{box}" role="img" aria-label="Vidi, Vidhyut Gopinath">\n'
            f'<title>Vidi — Vidhyut Gopinath</title>\n{paths(kind, ink, accent)}\n</svg>\n')


def raster(kind, width, ink, accent):
    """Render the same contours at 2x, retaining a transparent background."""
    bx, by, bw, bh = MODEL[kind]["viewBox"]
    height = round(width * bh / bw)
    scale = width * 2 / bw
    image = Image.new("RGBA", (width * 2, height * 2))
    for part in parts_for(kind):
        mask = Image.new("L", image.size)
        draw = ImageDraw.Draw(mask)
        for index, contour in enumerate(part["contours"]):
            draw.polygon([((x-bx)*scale, (y-by)*scale) for x, y in contour], fill=255 if index == 0 else 0)
        color = accent if part.get("accent") else ink
        image.paste(Image.new("RGBA", image.size, color), (0, 0), mask)
    return image.resize((width, height), Image.Resampling.LANCZOS)


def build():
    OUTPUT.mkdir(parents=True, exist_ok=True)
    themes = {
        "": ("#13263a", "#1763ad"),
        "-reverse": ("#f0f7fd", "#8dcbfa"),
        "-black": ("#000000", "#000000"),
        "-white": ("#ffffff", "#ffffff"),
    }
    kit_files = []
    for kind in ["wordmark", "stamp"]:
        for suffix, (ink, accent) in themes.items():
            name = f"vidi-{kind}{suffix}"
            content = svg(kind, ink, accent)
            (BRAND / f"{name}.svg").write_text(content)
            (OUTPUT / f"{name}.svg").write_text(content)
            raster(kind, 2048 if kind == "wordmark" else 1024, ink, accent).save(OUTPUT / f"{name}.png")
            kit_files.extend([f"{name}.svg", f"{name}.png"])

    symbols = []
    for kind in ["wordmark", "stamp"]:
        box = " ".join(map(str, MODEL[kind]["viewBox"]))
        symbols.append(f'<symbol id="{kind}" viewBox="{box}">\n{paths(kind, "currentColor", "var(--accent, currentColor)")}\n</symbol>')
    (BRAND / "vidi-sprite.svg").write_text('<svg xmlns="http://www.w3.org/2000/svg">\n' + "\n".join(symbols) + '\n</svg>\n')

    favicon = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="-4 -12 104 104">\n'
               '<rect x="-4" y="-12" width="104" height="104" rx="19" fill="#e2effa"/>\n'
               + paths("stamp", "#13263a", "#1763ad") + '\n</svg>\n')
    (BRAND / "vidi-favicon.svg").write_text(favicon)
    (OUTPUT / "vidi-favicon.svg").write_text(favicon)
    icon = Image.new("RGBA", (512, 512), "#e2effa")
    icon.alpha_composite(raster("stamp", 512, "#13263a", "#1763ad"))
    icon.resize((180, 180), Image.Resampling.LANCZOS).save(BRAND / "vidi-apple-touch-icon.png")
    icon.save(OUTPUT / "vidi-app-icon.png")
    icon.save(OUTPUT / "vidi-favicon.ico", sizes=[(16,16),(32,32),(48,48),(64,64)])
    kit_files.extend(["vidi-favicon.svg", "vidi-app-icon.png", "vidi-favicon.ico"])

    # This module is consumed by the interactive canvas; it contains no font dependency.
    exported = {"width": 192, "height": 76, "paths": [{"d": path_data(p), "accent": bool(p.get("accent"))} for p in MODEL["parts"]]}
    (ROOT / "assets/js/vidi-brand.js").write_text(
        '// Generated by scripts/build-brand.py from assets/brand/geometry.json.\n'
        '// Edit the geometry master, then rebuild.\n'
        'export const VIDI_WORDMARK = ' + json.dumps(exported, indent=2) + ';\n'
    )

    # A useful presentation of the logo itself, with real one-color and small-size examples.
    board = Image.new("RGB", (1600, 1040), "#edf4fa")
    draw = ImageDraw.Draw(board)
    font_path = ROOT / "assets/fonts/sofia-sans-latin.woff2"
    def label(x, y, value, size=24, color="#526a81"):
        draw.text((x, y), value, font=ImageFont.truetype(str(font_path), size), fill=color)
    def place(kind, width, x, y, ink="#13263a", accent="#1763ad"):
        art = raster(kind, width, ink, accent)
        board.paste(art, (x, y), art)
    label(80, 54, "VIDI / A PERSONAL ENGINEERING SIGNATURE", 22)
    label(80, 90, "Vidhyut Gopinath", 36, "#13263a")
    draw.line((80, 152, 1520, 152), fill="#c0d1e1", width=2)
    place("wordmark", 930, 74, 228)
    place("stamp", 230, 1190, 236)
    label(1190, 510, "Compact vi signature", 22)
    label(80, 640, "A connected vi. A chamfered d. One precise contact.", 27, "#13263a")
    draw.rectangle((0, 720, 800, 1040), fill="#071a30")
    label(80, 758, "ONE COLOR / REVERSED", 19, "#91abc3")
    place("wordmark", 400, 74, 815, "#ffffff", "#ffffff")
    label(880, 758, "ONE COLOR / SMALL SIZES", 19)
    place("wordmark", 270, 874, 816, "#000000", "#000000")
    for width, x in [(64, 1250), (32, 1354), (16, 1430)]:
        place("stamp", width, x, 836, "#13263a", "#13263a")
        label(x, 928, f"{width}px", 19)
    board.save(OUTPUT / "Vidi_Identity_Preview.png", optimize=True)

    guide = '''# Vidi — Vidhyut Gopinath

An original personal wordmark drawn as vector contours. The v and first i share one continuous route; the d uses a chamfered enclosure and open counter. A square contact identifies the compact vi signature. No font is required to use the finished artwork.

## Files

- vidi-wordmark.svg: primary navy and blue wordmark, transparent.
- vidi-stamp.svg: compact vi signature for avatars, slide corners, and small spaces.
- -reverse variants: white with a sky-blue contact for dark surfaces.
- -black and -white variants: strictly one color for print, engraving, or embroidery.
- PNG variants: transparent, 2048px wordmarks and 1024px stamps.
- vidi-app-icon.png and vidi-favicon.ico: ready-to-use icons.

## Use

Use the wordmark when the name should be read. Use the stamp at small sizes. Keep your full professional name nearby when introducing yourself to an unfamiliar audience.

Give the wordmark at least one stem-width of clear space (14 units on its 192-unit canvas). Recommended minimum wordmark width: 72px on screen or 20mm in print. The stamp remains recognizable at 16px; use 24px or larger where space allows. Keep the proportions and the gap above the contact intact.

Primary colors: navy #13263A and blue #1763AD. Reversed colors: white #F0F7FD and sky blue #8DCBFA. The identity also works entirely in black or white. Avoid gradients, outlines, shadows, rotating the logo, changing individual letter spacing, or adding stock circuitry around it. The portfolio's particle treatment is an expressive application; use the clean vector master for formal documents.

## Editing and rebuilding

The source is portfolio/assets/brand/geometry.json. Run portfolio/scripts/build-brand.py with Python and Pillow to regenerate vector assets, canvas geometry, this kit, and the preview. The site header, résumé, particle signature, and social card use this same geometry. No external fonts, services, or image-generation model are needed to reproduce the logo.
'''
    (BRAND / "README.md").write_text(guide)
    (OUTPUT / "README.md").write_text(guide)
    (OUTPUT / "geometry.json").write_text(json.dumps(MODEL, indent=2) + "\n")
    kit_files.extend(["README.md", "geometry.json", "Vidi_Identity_Preview.png"])
    with ZipFile(OUTPUT / "Vidi_Identity_Kit.zip", "w", ZIP_DEFLATED) as archive:
        for name in kit_files:
            archive.write(OUTPUT / name, f"Vidi_Identity/{name}")
    print(f"Built {len(kit_files)} reusable files, the vector sprite, and canvas geometry.")


if __name__ == "__main__":
    build()
